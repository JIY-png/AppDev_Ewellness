-- E-Wellness EHR System - Supabase Database Schema
-- Run this script in the Supabase SQL Editor (Dashboard > SQL Editor > New query)

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================
-- PATIENTS TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    gender TEXT NOT NULL,
    birth_date TEXT NOT NULL,
    contact_no TEXT DEFAULT '',
    barangay TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_patients_id ON patients(id);
CREATE INDEX IF NOT EXISTS idx_patients_name ON patients(last_name, first_name);

-- ============================================
-- RECORDS TABLE (Health Records / Vitals)
-- ============================================
CREATE TABLE IF NOT EXISTS records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
    "A" TEXT, -- Date (YYYY-MM-DD)
    "B" TEXT, -- Time (HH:MM AM/PM)
    "C" TEXT, -- FirstName
    "D" TEXT, -- LastName
    "E" INTEGER, -- Age
    "F" TEXT, -- Gender
    "G" TEXT, -- BloodPressure (e.g. 120/80)
    "H" INTEGER, -- HeartRate_BPM
    "I" INTEGER, -- OxygenSaturation_pct
    "J" FLOAT, -- BodyTemp_C
    "K" FLOAT, -- Weight_kg
    "L" FLOAT, -- Height_cm
    "M" FLOAT, -- BMI
    bmi_category TEXT,
    status TEXT,
    remarks TEXT,
    created_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_records_patient_id ON records(patient_id);
CREATE INDEX IF NOT EXISTS idx_records_status ON records(status);
CREATE INDEX IF NOT EXISTS idx_records_created_at ON records(created_at);

-- ============================================
-- ADMIN_USERS TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS admin_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    username TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admin_users_username ON admin_users(username);

-- ============================================
-- ACCESS_LOGS TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS access_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" TEXT NOT NULL,
    role TEXT NOT NULL,
    action TEXT NOT NULL,
    date_time TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_access_logs_date_time ON access_logs(date_time DESC);

